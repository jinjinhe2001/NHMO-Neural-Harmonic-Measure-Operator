"""MCB-B Poisson evaluation of NHMO (paper Tables 2 and 3).

For each test (shape, problem) pair:
    u_pred(p) = <h, K_theta(p, .; Omega)> + v_phi(p; Omega, f)
at every interior tet vertex, compared with the FEM reference `sol` released by
NGF (Yoo et al., NeurIPS 2025) on the `unknown_shape_unknown_prob` split
(20 shapes x 16 problems per category). K_theta is the per-category kernel
checkpoint, v_phi the per-category lift checkpoint.

Two evaluation paths:
  default : the reference arithmetic used for the paper tables (trimesh SDF
            grid, per-query lift forward, per-chunk boundary quadrature).
  --fast  : the optimized inference path of `nhmo.core.fast_inference`
            (GPU SDF grid, folded K_eff, query-folded lift). Mathematically the
            same model; small differences come from the GPU SDF grid and from
            fp32 rounding.

`--seed` (default 0) seeds the surface samples, interior anchors and source-probe
subset drawn for each shape.

Usage:
    python -m nhmo.eval.mcb_lift --category nut \\
        --kernel-ckpt $CKPT/3d/kernel_nut.pt --lift-ckpt $CKPT/3d/lift_nut.pt \\
        --out results/mcb_nut_seed0.json

`--problems-root DIR` evaluates every `DIR/<category>/<shape>/<problem>/sol.npz`
instead of the NGF split (used for the coefficient-OOD problems generated by
tools/gen_ood3d.py).
"""
from __future__ import annotations

import argparse
import json
import os
import time
from pathlib import Path

import numpy as np
import torch
from torch import Tensor

from nhmo.core.fast_inference import (
    ShapeCache, encode_shape, precompute_shape, solve_cached, source_probe,
)
from nhmo.core.kernel import HarmonicMeasureField, ShapeLatent
from nhmo.core.source_lift import PoissonLiftModule
from nhmo.data.mcb_loader import load_mcb_eval_fields
from nhmo.geometry.sdf import trilinear_interp


def load_models(kernel_ckpt: str, lift_ckpt: str, device: torch.device):
    """Rebuild K_theta and v_phi from (possibly stripped) release checkpoints."""
    ckpt_k = torch.load(kernel_ckpt, map_location="cpu", weights_only=False)
    cfg = ckpt_k["cfg"]
    kernel = HarmonicMeasureField(
        encoder_cfg=cfg["encoder"], kernel_head_cfg=cfg["kernel_head"],
        normalize=cfg["kernel"]["normalize"],
    ).to(device)
    kernel.load_state_dict(ckpt_k["model_state_dict"])
    kernel.eval()
    ckpt_l = torch.load(lift_ckpt, map_location="cpu", weights_only=False)
    lift_cfg = ckpt_l.get("lift_cfg", {"d_model": int(cfg["kernel_head"]["d_model"])})
    lift = PoissonLiftModule(**lift_cfg).to(device)
    lift.load_state_dict(ckpt_l["lift_state_dict"])
    lift.eval()
    if bool(ckpt_l.get("use_local_baseline", False)):
        raise ValueError("lift checkpoints trained with the local-ball baseline are not supported")
    return kernel, lift, cfg, lift_cfg


def evaluate_one_bc(
    kernel: HarmonicMeasureField,
    lift: PoissonLiftModule,
    sol_path: Path,
    sh: ShapeCache,
    n_queries: int,            # -1 = all interior tet vertices (NGF protocol)
    n_source_probe: int,
    q_batch: int,
    device: torch.device,
    seed: int | None = 0,
) -> dict:
    """Reference evaluation of one (shape, problem) pair on a pre-encoded shape."""
    f = load_mcb_eval_fields(str(sol_path))
    sol = np.asarray(f.sol).reshape(-1)
    src = np.asarray(f.source_term).reshape(-1)
    bd_inds = np.asarray(f.bd_v_inds)
    bd_vals = np.asarray(f.bd_v_vals)

    interior_inds = sh.interior_inds
    if n_queries < 0 or n_queries >= len(interior_inds):
        sel = interior_inds
    else:
        sel = np.random.RandomState(0).choice(interior_inds, n_queries, replace=False)
    p_model_np = (sh.v_tet[sel] - sh.center) * sh.scale
    p_model = torch.from_numpy(p_model_np.astype(np.float32)).to(device)
    p_wos = torch.from_numpy(((p_model_np + 1.0) * 0.5).astype(np.float32)).to(device)
    sdf_at_p = trilinear_interp(sh.sdf_grid_wos.unsqueeze(0), p_wos.unsqueeze(0)).squeeze(0)

    # h at the model's surface samples: nearest boundary tet vertex.
    bd_pts_model = (sh.v_tet[bd_inds] - sh.center) * sh.scale
    surf_np = sh.surface.squeeze(0).cpu().numpy()
    diffs = surf_np[:, None, :] - bd_pts_model[None, :, :]
    nearest = np.argmin((diffs * diffs).sum(axis=-1), axis=-1)
    h_at_surf = torch.from_numpy(bd_vals[nearest].astype(np.float32)).to(device)

    f_probe_pos, f_probe = source_probe(sh, src, n_source_probe, seed)

    Q = p_model.shape[0]
    u_h_chunks, v_phi_chunks = [], []
    with torch.no_grad():
        src_tokens = lift.encode_source(f_probe_pos.unsqueeze(0), f_probe.unsqueeze(0))
        for s in range(0, Q, q_batch):
            e = min(Q, s + q_batch)
            qb = e - s
            p_b = p_model[s:e]
            surf_q = sh.surface.expand(qb, -1, -1)
            surf_n_q = sh.surface_normals.expand(qb, -1, -1)
            sl_q = ShapeLatent(tokens=sh.shape_latent.tokens.expand(qb, -1, -1))
            N_s = surf_q.shape[1]
            log_K_tilde = kernel.log_kernel(p_b, surf_q, surf_n_q, sl_q)
            weight = torch.full((qb, N_s), sh.total_area / N_s, device=device, dtype=p_b.dtype)
            log_w = torch.log(weight + 1e-30)
            log_Z = torch.logsumexp(log_K_tilde + log_w, dim=-1)
            K_norm = torch.exp(log_K_tilde - log_Z.unsqueeze(-1))
            u_h_chunks.append((weight * K_norm * h_at_surf.unsqueeze(0)).sum(dim=-1))
            v_phi_chunks.append(lift(p_b, sh.shape_latent.tokens.expand(qb, -1, -1),
                                     src_tokens.expand(qb, -1, -1), sdf_at_p[s:e]))
    u_h = torch.cat(u_h_chunks)
    v_phi = torch.cat(v_phi_chunks)
    u_true = torch.from_numpy(sol[sel].astype(np.float32)).to(device)
    return _record(sol_path, u_h, v_phi, u_true)


def evaluate_one_bc_fast(lift, sol_path: Path, cache: ShapeCache, n_source_probe: int,
                         device: torch.device, seed: int | None = 0) -> dict:
    """Fast-path evaluation (all interior vertices) on a precomputed cache."""
    f = load_mcb_eval_fields(str(sol_path))
    u_h, v_phi = solve_cached(lift, cache, f.bd_v_inds, f.bd_v_vals, f.source_term,
                              n_source_probe=n_source_probe, seed=seed, fast=True)
    u_true = torch.from_numpy(np.asarray(f.sol).reshape(-1)[cache.interior_inds]
                              .astype(np.float32)).to(device)
    return _record(sol_path, u_h, v_phi, u_true)


def _record(sol_path: Path, u_h: Tensor, v_phi: Tensor, u_true: Tensor) -> dict:
    u_pred = u_h + v_phi

    def rl2(a: Tensor, b: Tensor) -> float:
        return float((torch.norm(a - b) / (torch.norm(b) + 1e-12)).item())

    return {
        "shape_id": sol_path.parent.parent.name,
        "bc_config": sol_path.parent.name,
        "n_queries": int(u_true.shape[0]),
        "rel_l2_full": rl2(u_pred, u_true),
        "rel_l2_laplace_only": rl2(u_h, u_true),
        "rel_l2_lift_only": rl2(v_phi, u_true),
        "u_h_abs_mean": float(u_h.abs().mean().item()),
        "v_phi_abs_mean": float(v_phi.abs().mean().item()),
        "u_pred_mean": float(u_pred.mean().item()),
        "u_true_mean": float(u_true.mean().item()),
    }


def split_pairs(mcb_root: Path, category: str, split: str) -> dict[str, list[Path]]:
    """(shape -> sol.npz paths) exactly as listed in the NGF split file."""
    split_file = mcb_root / "splits" / category / f"{split}.txt"
    if not split_file.exists():
        raise FileNotFoundError(f"Split file missing: {split_file}")
    by_shape: dict[str, list[Path]] = {}
    for line in split_file.read_text().strip().splitlines():
        parts = Path(line).parts
        if len(parts) < 5 or parts[-1] != "sol.npz":
            continue
        sid, bc_config = parts[-3], parts[-2]
        sol_npz = mcb_root / "ngf_solutions" / category / sid / bc_config / "sol.npz"
        if sol_npz.exists():
            by_shape.setdefault(sid, []).append(sol_npz)
    return by_shape


def tree_pairs(root: Path, category: str) -> dict[str, list[Path]]:
    """(shape -> sol.npz paths) for a `root/<category>/<shape>/<problem>/sol.npz` tree."""
    by_shape: dict[str, list[Path]] = {}
    for sd in sorted((root / category).iterdir()):
        probs = sorted(sd.glob("*/sol.npz"))
        if probs:
            by_shape[sd.name] = probs
    return by_shape


def summarize(vals: np.ndarray) -> dict:
    return {"mean": float(vals.mean()), "median": float(np.median(vals)),
            "p95": float(np.percentile(vals, 95)), "max": float(vals.max())}


def main() -> int:
    pa = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    pa.add_argument("--kernel-ckpt", required=True)
    pa.add_argument("--lift-ckpt", required=True)
    pa.add_argument("--mcb-root", default=os.environ.get("MCB_ROOT", "data/MCB_benchmark"),
                    help="root with splits/ and ngf_solutions/ (env MCB_ROOT)")
    pa.add_argument("--category", required=True)
    pa.add_argument("--split", default="unknown_shape_unknown_prob")
    pa.add_argument("--problems-root", default=None,
                    help="evaluate DIR/<category>/<shape>/<problem>/sol.npz instead of the split")
    pa.add_argument("--n-shapes", type=int, default=20)
    pa.add_argument("--bcs-per-shape", type=int, default=16)
    pa.add_argument("--n-queries", type=int, default=-1,
                    help="-1 = all interior tet vertices (NGF protocol)")
    pa.add_argument("--n-source-probe", type=int, default=1024)
    pa.add_argument("--q-batch", type=int, default=1024,
                    help="queries per kernel/lift chunk (4096 needs ~70 GB of GPU memory)")
    pa.add_argument("--grid-size", type=int, default=32)
    pa.add_argument("--n-surface", type=int, default=2000)
    pa.add_argument("--n-interior", type=int, default=512)
    pa.add_argument("--seed", type=int, default=0,
                    help="seed of the per-shape surface samples, anchors and source probes "
                         "(default 0; -1 = unseeded)")
    pa.add_argument("--fast", action="store_true",
                    help="use the optimized inference path (nhmo.core.fast_inference)")
    pa.add_argument("--out", default=None)
    args = pa.parse_args()
    seed = None if args.seed < 0 else args.seed

    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    kernel, lift, cfg, lift_cfg = load_models(args.kernel_ckpt, args.lift_ckpt, device)
    print(f"[mcb-eval] kernel={args.kernel_ckpt}\n[mcb-eval] lift={args.lift_ckpt} lift_cfg={lift_cfg}")

    mcb_root = Path(args.mcb_root)
    if args.problems_root:
        by_shape = tree_pairs(Path(args.problems_root), args.category)
    else:
        by_shape = split_pairs(mcb_root, args.category, args.split)
    shape_ids = list(by_shape.keys())[: args.n_shapes]
    n_pairs = sum(min(args.bcs_per_shape, len(by_shape[s])) for s in shape_ids)
    print(f"[mcb-eval] category={args.category} shapes={len(shape_ids)} pairs={n_pairs} "
          f"seed={seed} fast={args.fast}")

    results: list = []
    skipped = 0
    t0 = time.time()
    k = 0
    for sid in shape_ids:
        bc_paths = by_shape[sid][: args.bcs_per_shape]
        try:
            if args.fast:
                sh = precompute_shape(kernel, bc_paths[0], grid_size=args.grid_size,
                                      n_surface=args.n_surface, n_interior=args.n_interior,
                                      device=device, seed=seed, fast=True)
            else:
                sh = encode_shape(kernel, bc_paths[0], args.grid_size, args.n_surface,
                                  args.n_interior, device, seed=seed)
        except Exception as e:  # keep going; report the count
            skipped += len(bc_paths)
            print(f"[mcb-eval] {sid}: shape encode FAIL {type(e).__name__} {e!s:.100}")
            continue
        for path in bc_paths:
            k += 1
            try:
                if args.fast:
                    r = evaluate_one_bc_fast(lift, path, sh, args.n_source_probe, device, seed)
                else:
                    r = evaluate_one_bc(kernel, lift, path, sh, args.n_queries,
                                        args.n_source_probe, args.q_batch, device, seed)
            except Exception as e:
                skipped += 1
                print(f"[mcb-eval] {sid}/{path.parent.name}: FAIL {type(e).__name__} {e!s:.100}")
                continue
            results.append(r)
            print(f"[mcb-eval] [{k}/{n_pairs}] {sid[:12]}/{path.parent.name[:25]:25s} "
                  f"relL2={r['rel_l2_full']:.4f} kernel_only={r['rel_l2_laplace_only']:.4f} "
                  f"Q={r['n_queries']} ({time.time() - t0:.0f}s)", flush=True)

    print(f"\n[mcb-eval] DONE: {len(results)} pairs, skipped={skipped}, {time.time() - t0:.0f}s")
    if not results:
        return 1
    rl2 = np.array([r["rel_l2_full"] for r in results])
    rl2_l = np.array([r["rel_l2_laplace_only"] for r in results])
    agg = {"full": summarize(rl2), "kernel_only": summarize(rl2_l)}
    print(f"{'':<24}{'mean':>9}{'median':>9}{'p95':>9}")
    for name, v in agg.items():
        print(f"{name:<24}{v['mean']:>9.4f}{v['median']:>9.4f}{v['p95']:>9.4f}")
    if args.out:
        Path(args.out).parent.mkdir(parents=True, exist_ok=True)
        Path(args.out).write_text(json.dumps({
            "kernel_ckpt": args.kernel_ckpt, "lift_ckpt": args.lift_ckpt,
            "category": args.category, "split": args.split, "problems_root": args.problems_root,
            "seed": seed, "fast": args.fast, "n_evaluated": len(results), "skipped": skipped,
            "aggregate": agg, "args": vars(args), "per_pair": results,
        }, indent=1))
        print(f"[mcb-eval] wrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
